use board_core::StrokePoint;
use serde::{Deserialize, Serialize};

/// One labeled example; several examples may share a label. Coordinates use screen y-down.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct InkTemplate {
    pub text: String,
    pub strokes: Vec<Vec<StrokePoint>>,
}

fn template(text: &str, lines: &[&[(f32, f32)]]) -> InkTemplate {
    InkTemplate {
        text: text.into(),
        strokes: lines
            .iter()
            .map(|line| {
                line.iter()
                    .enumerate()
                    .map(|(i, &(x, y))| StrokePoint {
                        x,
                        y,
                        time: i as f64,
                        pressure: 0.5,
                    })
                    .collect()
            })
            .collect(),
    }
}

